import AppKit
import Testing

@testable import DictApp

/// Uses a private named pasteboard, never the general one.
@MainActor
struct ClipboardGatewayTests {
  let pasteboard = NSPasteboard(name: NSPasteboard.Name("au.ibra.dict.tests.\(UUID().uuidString)"))
  var gateway: ClipboardGateway { ClipboardGateway(pasteboard: pasteboard) }

  func put(_ text: String) {
    pasteboard.clearContents()
    pasteboard.setString(text, forType: .string)
  }

  @Test func restoresEveryTypeAfterTheClipboardChanged() {
    pasteboard.clearContents()
    let item = NSPasteboardItem()
    item.setString("original", forType: .string)
    item.setData(Data([1, 2, 3]), forType: NSPasteboard.PasteboardType("com.example.custom"))
    pasteboard.writeObjects([item])
    let snapshot = gateway.snapshot()

    put("copied")
    gateway.restore(snapshot)

    #expect(pasteboard.string(forType: .string) == "original")
    #expect(
      pasteboard.data(forType: NSPasteboard.PasteboardType("com.example.custom"))
        == Data([1, 2, 3]))
    #expect(pasteboard.types?.contains(ClipboardGateway.autoGeneratedType) == true)
  }

  @Test func doesNotRestoreWhenNothingChanged() {
    put("original")
    let snapshot = gateway.snapshot()
    let before = pasteboard.changeCount

    gateway.restore(snapshot)

    #expect(pasteboard.changeCount == before)
    #expect(pasteboard.types?.contains(ClipboardGateway.autoGeneratedType) == false)
  }

  @Test func restoresAnEmptyClipboardToEmpty() {
    pasteboard.clearContents()
    let snapshot = gateway.snapshot()
    put("copied")

    gateway.restore(snapshot)

    #expect(pasteboard.string(forType: .string) == nil)
  }

  @Test func waitsForAChangeWithTypes() async {
    put("original")
    let start = pasteboard.changeCount
    let pasteboard = self.pasteboard
    Task { @MainActor in
      try? await Task.sleep(for: .milliseconds(30))
      pasteboard.clearContents()
      try? await Task.sleep(for: .milliseconds(30))
      pasteboard.setString("copied", forType: .string)
    }

    let copied = await gateway.waitForCopy(since: start, timeout: .milliseconds(500))

    #expect(copied)
    #expect(pasteboard.string(forType: .string) == "copied")
  }

  @Test func waitTimesOutWhenNothingIsCopied() async {
    put("original")
    let copied = await gateway.waitForCopy(
      since: pasteboard.changeCount, timeout: .milliseconds(40))
    #expect(!copied)
  }

  @Test func readsCopiedText() {
    put("copied")
    #expect(gateway.copiedContent() == .text("copied"))
  }

  @Test func neverReadsConcealedContent() {
    pasteboard.clearContents()
    let item = NSPasteboardItem()
    item.setString("secret", forType: .string)
    item.setData(Data(), forType: ClipboardGateway.concealedType)
    pasteboard.writeObjects([item])

    #expect(gateway.copiedContent() == .concealed)
  }

  @Test func fileURLsAreNotText() {
    pasteboard.clearContents()
    pasteboard.writeObjects([URL(fileURLWithPath: "/tmp/example.txt") as NSURL])

    #expect(gateway.copiedContent() == .fileURL)
  }

  @Test func lateCopyIsUndone() async {
    put("original")
    let snapshot = gateway.snapshot()
    let pasteboard = self.pasteboard
    Task { @MainActor in
      try? await Task.sleep(for: .milliseconds(50))
      pasteboard.clearContents()
      pasteboard.setString("late", forType: .string)
    }

    await gateway.undoLateCopy(of: snapshot, window: .milliseconds(300))

    #expect(pasteboard.string(forType: .string) == "original")
  }

  @Test func userCopiesDuringTheWindowAreKept() async {
    put("original")
    let snapshot = gateway.snapshot()
    let pasteboard = self.pasteboard
    Task { @MainActor in
      try? await Task.sleep(for: .milliseconds(50))
      pasteboard.clearContents()
      pasteboard.setString("late", forType: .string)
      pasteboard.clearContents()
      pasteboard.setString("the user's own copy", forType: .string)
    }

    await gateway.undoLateCopy(of: snapshot, window: .milliseconds(300))

    #expect(pasteboard.string(forType: .string) == "the user's own copy")
  }

  @Test func transientWritesAreMarked() {
    let count = gateway.writeTransient("result")
    #expect(count == pasteboard.changeCount)
    #expect(pasteboard.string(forType: .string) == "result")
    #expect(pasteboard.types?.contains(ClipboardGateway.transientType) == true)
  }
}
