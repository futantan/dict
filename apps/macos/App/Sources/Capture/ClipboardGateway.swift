import AppKit

/// Every clipboard read and write goes through here (architecture 3.7).
/// `ReplaceWriter` reuses it for pasting. Tests pass a private named pasteboard.
@MainActor
final class ClipboardGateway {
  /// Marks data we put back, so clipboard managers can skip it (nspasteboard.org).
  static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
  /// Marks data that exists only for a moment, such as a result written for pasting.
  static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
  /// Marks secrets written by password managers; never read.
  static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")

  let pasteboard: NSPasteboard

  init(pasteboard: NSPasteboard = .general) {
    self.pasteboard = pasteboard
  }

  var changeCount: Int { pasteboard.changeCount }

  /// The macOS 15.4 clipboard privacy setting denies this app.
  var isAccessDenied: Bool {
    if #available(macOS 15.4, *) { return pasteboard.accessBehavior == .alwaysDeny }
    return false
  }

  /// Reads every type of every item. This forces lazily provided data, so call it only right
  /// before a copy or paste is triggered.
  func snapshot() -> ClipboardSnapshot {
    let items = (pasteboard.pasteboardItems ?? []).map { item in
      item.types.compactMap { type in item.data(forType: type).map { (type, $0) } }
    }
    return ClipboardSnapshot(changeCount: pasteboard.changeCount, items: items)
  }

  /// Puts the snapshot back if the clipboard changed since, with every type and its data as
  /// they were plus the empty auto-generated marker. With `copy`, the change count our copy
  /// left: anything later was written by someone else and is kept.
  func restore(_ snapshot: ClipboardSnapshot, after copy: Int? = nil) {
    guard pasteboard.changeCount != snapshot.changeCount else { return }
    if let copy, pasteboard.changeCount != copy {
      Log.capture.info("clipboard written again after the copy: not restored")
      return
    }
    pasteboard.clearContents()
    let items = snapshot.items.map { entries in
      let item = NSPasteboardItem()
      for (type, data) in entries { item.setData(data, forType: type) }
      item.setData(Data(), forType: Self.autoGeneratedType)
      return item
    }
    if !items.isEmpty { pasteboard.writeObjects(items) }
  }

  /// Waits until the change count moves past `start` and the clipboard holds what a copy of
  /// a selection leaves: readable plain text, a file URL or concealed data. Apps often clear
  /// first and write after; Safari writes its rich types before the plain text and may
  /// declare the text before it can be read (measured). Checks every 5 ms; returns the
  /// change count the copy left, or nil when it timed out or was cancelled.
  func waitForCopy(since start: Int, timeout: Duration) async -> Int? {
    let clock = ContinuousClock()
    let deadline = clock.now + timeout
    while true {
      if pasteboard.changeCount != start, copyHasLanded() { return pasteboard.changeCount }
      guard clock.now < deadline else { return nil }
      do {
        try await Task.sleep(for: .milliseconds(5))
      } catch {
        return nil
      }
    }
  }

  /// Concealed content is recognised by its type alone, never read.
  private func copyHasLanded() -> Bool {
    let types = pasteboard.types ?? []
    if types.contains(Self.concealedType) || types.contains(.fileURL) { return true }
    return types.contains(.string) && pasteboard.string(forType: .string) != nil
  }

  /// What a copy put on the clipboard. Concealed content is reported but never read.
  func copiedContent() -> CopiedContent {
    let types = pasteboard.types ?? []
    if types.contains(Self.concealedType) { return .concealed }
    if types.contains(.fileURL) { return .fileURL }
    guard let text = pasteboard.string(forType: .string) else { return .none }
    return .text(text)
  }

  /// The richest formatted flavor a copy left, RTFD, RTF or HTML, as data: reading HTML
  /// needs WebKit, so it is parsed only if a replacement uses it (architecture 4.7). Chrome
  /// copies HTML and no RTF (measured). Never read for concealed content.
  func richestFlavor() -> RichSource? {
    let types = pasteboard.types ?? []
    guard !types.contains(Self.concealedType) else { return nil }
    for type in [NSPasteboard.PasteboardType.rtfd, .rtf, .html] where types.contains(type) {
      if let data = pasteboard.data(forType: type) { return .pasteboard(type, data) }
    }
    return nil
  }

  /// After a copy timed out, watches for `window`: if exactly one more change arrives (the
  /// late copy), puts the snapshot back. More than one change means the user copied; keep it.
  func undoLateCopy(of snapshot: ClipboardSnapshot, window: Duration) async {
    let start = pasteboard.changeCount
    let clock = ContinuousClock()
    let deadline = clock.now + window
    while clock.now < deadline {
      try? await Task.sleep(for: .milliseconds(20))
      let moved = pasteboard.changeCount - start
      if moved > 1 { return }
      if moved == 1 {
        restore(snapshot)
        return
      }
    }
  }

  /// Writes text that should not be remembered by clipboard managers, with RTF and HTML
  /// beside it in the same item when `rich` is given; returns the new count. Native text
  /// views paste the RTF, web views the HTML, plain-text editors the text (measured).
  @discardableResult
  func writeTransient(_ text: String, rich: RichPayload? = nil) -> Int {
    pasteboard.clearContents()
    let item = NSPasteboardItem()
    item.setString(text, forType: .string)
    if let rich {
      item.setData(rich.rtf, forType: .rtf)
      item.setString(rich.html, forType: .html)
    }
    item.setData(Data(), forType: Self.transientType)
    pasteboard.writeObjects([item])
    return pasteboard.changeCount
  }
}

struct ClipboardSnapshot: Sendable {
  let changeCount: Int
  let items: [[(NSPasteboard.PasteboardType, Data)]]
}

enum CopiedContent: Equatable, Sendable {
  case text(String)
  case fileURL
  case concealed
  case none
}
